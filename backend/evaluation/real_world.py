"""Real-world corpus benchmark: run the production baseline and report by category.

This is a MANUAL quality benchmark, not a CI step. Run on a machine with the
production music dependencies (Basic Pitch, pretty_midi, soundfile) and the
prepared corpus:

  python -m evaluation.datasets.prepare --corpus real_world_v1
  python -m evaluation.real_world --corpus real_world_v1

The first command downloads/slices/caches the pinned clips. The second runs
transcription + metrics and writes:
  evaluation/reports/real_world_v1.json
  evaluation/reports/real_world_v1.md
"""

from __future__ import annotations

import argparse
import json
import time
from pathlib import Path
from typing import Any

from evaluation.datasets import cache
from evaluation.transcription_metrics import Note, compute_note_metrics


def _load_clips(corpus: str) -> list[dict[str, Any]]:
    corpora_dir = Path(__file__).resolve().parent / "corpora"
    with open(corpora_dir / f"{corpus}.json") as fh:
        data = json.load(fh)
    return data["clips"]


def _load_reference_notes(prepared_dir: Path, clip_id: str) -> list[Note]:
    midi_path = prepared_dir / f"{clip_id}.mid"
    if not midi_path.exists():
        return []

    import pretty_midi

    pm = pretty_midi.PrettyMIDI(str(midi_path))
    return [
        Note(pitch=n.pitch, start=n.start, end=n.end, velocity=n.velocity)
        for inst in pm.instruments
        for n in inst.notes
        if not inst.is_drum
    ]


def run_benchmark(corpus: str) -> dict[str, Any]:
    prepared_dir = cache.cache_dir() / "prepared" / corpus
    clips = _load_clips(corpus)

    import sys

    backend_dir = str(Path(__file__).resolve().parent.parent)
    if backend_dir not in sys.path:
        sys.path.insert(0, backend_dir)
    from music_features import transcribe_audio

    results: list[dict[str, Any]] = []
    for clip in clips:
        clip_id = clip["id"]
        audio_path = prepared_dir / f"{clip_id}.wav"
        if not audio_path.exists():
            results.append({"id": clip_id, "status": "missing", "category": clip["category"]})
            continue
        audio_bytes = audio_path.read_bytes()
        ref_notes = _load_reference_notes(prepared_dir, clip_id)
        t0 = time.monotonic()
        try:
            tr = transcribe_audio(audio_bytes, fmt="wav")
            elapsed = time.monotonic() - t0
            pred_notes = [Note.from_dict(n) for n in tr.get("notes", [])]
            metrics = compute_note_metrics(pred_notes, ref_notes).to_dict() if ref_notes else None
            results.append(
                {
                    "id": clip_id,
                    "status": "ok",
                    "category": clip["category"],
                    "num_notes": tr["num_notes"],
                    "time_s": round(elapsed, 2),
                    "metrics": metrics,
                }
            )
        except Exception as exc:
            results.append(
                {
                    "id": clip_id,
                    "status": "error",
                    "category": clip["category"],
                    "message": str(exc),
                }
            )

    by_category: dict[str, dict[str, Any]] = {}
    for r in results:
        if r.get("status") != "ok" or not r.get("metrics"):
            continue
        cat = r["category"]
        by_category.setdefault(cat, []).append(r["metrics"]["note_f1"])

    summary = {
        "corpus": corpus,
        "clip_count": len(clips),
        "completed": sum(1 for r in results if r["status"] == "ok"),
        "by_category": {
            cat: {
                "clip_count": len(f1s),
                "macro_note_f1": round(sum(f1s) / len(f1s), 4),
            }
            for cat, f1s in by_category.items()
        },
        "results": results,
    }
    return summary


def _write_report(summary: dict[str, Any], corpus: str) -> tuple[str, str]:
    reports_dir = Path(__file__).resolve().parent / "reports"
    reports_dir.mkdir(parents=True, exist_ok=True)
    json_path = reports_dir / f"{corpus}.json"
    md_path = reports_dir / f"{corpus}.md"

    json_path.write_text(json.dumps(summary, indent=2))

    lines = [f"# Real-world evaluation: {corpus}", ""]
    lines.append(f"Clips: {summary['clip_count']}  Completed: {summary['completed']}")
    lines.append("")
    lines.append("## Results by category")
    lines.append("| Category | Clips | Macro note F1 |")
    lines.append("|----------|-------|---------------|")
    for cat, info in summary["by_category"].items():
        lines.append(f"| {cat} | {info['clip_count']} | {info['macro_note_f1']} |")
    lines.append("")
    lines.append(
        "> Generated by `python -m evaluation.real_world`. See PR description for full context."
    )
    md_path.write_text("\n".join(lines))

    return str(json_path), str(md_path)


def main() -> None:
    parser = argparse.ArgumentParser(description="Run real-world quality benchmark")
    parser.add_argument("--corpus", default="real_world_v1")
    args = parser.parse_args()
    summary = run_benchmark(args.corpus)
    j, m = _write_report(summary, args.corpus)
    print(json.dumps(summary.get("by_category", {}), indent=2))
    print(f"JSON: {j}")
    print(f"Markdown: {m}")


if __name__ == "__main__":
    main()
